//! Renders collected services as Rust, TypeScript or JSON. Output is a pure
//! function of the services and options, so it is byte-for-byte stable.

use core::fmt::Write as _;

use crate::{Lang, Options, Service};

const HEADER: &str = "// @generated by protoc-gen-rpc-manifest. DO NOT EDIT.\n";

/// Renders `services` in `lang`.
pub fn render(lang: Lang, services: &[Service], options: &Options) -> String {
    match lang {
        Lang::Rust => rust(services, &options.crate_path),
        Lang::Ts => ts(services),
        Lang::Json => json(services),
    }
}

/// A Rust string literal: `Debug` escapes `"`, `\` and control characters
/// in Rust syntax.
struct RustStr<'a>(&'a str);

impl core::fmt::Display for RustStr<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "{:?}", self.0)
    }
}

fn pascal(snake: &str) -> String {
    snake
        .split('_')
        .flat_map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|h| h.to_ascii_uppercase())
                .into_iter()
                .chain(c)
        })
        .collect()
}

// `write!` to a `String` can't fail, hence the ignored results below.
fn rust(services: &[Service], krate: &str) -> String {
    let mut o = String::with_capacity(512 + services.len() * 1024);
    o.push_str(HEADER);
    o.push_str("\n/// Every RPC service in the selected protos, sorted by full name.\n");
    o.push_str("#[rustfmt::skip]\n");
    let _ = writeln!(o, "pub static SERVICES: &[{krate}::Service] = &[");
    for s in services {
        let _ = writeln!(o, "    {krate}::Service {{");
        let _ = writeln!(o, "        full_name: {},", RustStr(&s.full_name));
        let _ = writeln!(o, "        package: {},", RustStr(&s.package));
        let _ = writeln!(o, "        name: {},", RustStr(&s.name));
        let _ = writeln!(o, "        alias: {},", RustStr(&s.alias));
        let _ = writeln!(o, "        comments: {},", RustStr(&s.comments));
        o.push_str("        methods: &[\n");
        for m in &s.methods {
            let _ = writeln!(o, "            {krate}::Method {{");
            let _ = writeln!(o, "                name: {},", RustStr(&m.name));
            let _ = writeln!(o, "                input_type: {},", RustStr(&m.input_type));
            let _ = writeln!(
                o,
                "                output_type: {},",
                RustStr(&m.output_type)
            );
            let _ = writeln!(
                o,
                "                idempotency: {krate}::Idempotency::{},",
                pascal(m.idempotency)
            );
            let _ = writeln!(
                o,
                "                streaming: {krate}::Streaming::{},",
                pascal(m.streaming)
            );
            let _ = writeln!(o, "                comments: {},", RustStr(&m.comments));
            o.push_str("            },\n");
        }
        o.push_str("        ],\n    },\n");
    }
    o.push_str("];\n");
    o
}

/// A JSON string literal, which is also a valid TS one.
fn js(s: &str) -> String {
    serde_json::Value::from(s).to_string()
}

const TS_TYPES: &str = r#"
export type Idempotency = "unknown" | "no_side_effects" | "idempotent";
export type Streaming = "unary" | "client" | "server" | "bidi";

export interface RpcMethod {
  readonly name: string;
  readonly inputType: string;
  readonly outputType: string;
  readonly idempotency: Idempotency;
  readonly streaming: Streaming;
  readonly comments: string;
}

export interface RpcService {
  readonly fullName: string;
  readonly package: string;
  readonly name: string;
  readonly alias: string;
  readonly comments: string;
  readonly methods: readonly RpcMethod[];
}

/** Every RPC service in the selected protos, sorted by full name. */
"#;

fn ts(services: &[Service]) -> String {
    let mut o = String::with_capacity(1024 + services.len() * 1024);
    o.push_str(HEADER);
    o.push_str(TS_TYPES);
    o.push_str("export const SERVICES: readonly RpcService[] = [\n");
    for s in services {
        o.push_str("  {\n");
        let _ = writeln!(o, "    fullName: {},", js(&s.full_name));
        let _ = writeln!(o, "    package: {},", js(&s.package));
        let _ = writeln!(o, "    name: {},", js(&s.name));
        let _ = writeln!(o, "    alias: {},", js(&s.alias));
        let _ = writeln!(o, "    comments: {},", js(&s.comments));
        o.push_str("    methods: [\n");
        for m in &s.methods {
            o.push_str("      {\n");
            let _ = writeln!(o, "        name: {},", js(&m.name));
            let _ = writeln!(o, "        inputType: {},", js(&m.input_type));
            let _ = writeln!(o, "        outputType: {},", js(&m.output_type));
            let _ = writeln!(o, "        idempotency: {},", js(m.idempotency));
            let _ = writeln!(o, "        streaming: {},", js(m.streaming));
            let _ = writeln!(o, "        comments: {},", js(&m.comments));
            o.push_str("      },\n");
        }
        o.push_str("    ],\n  },\n");
    }
    o.push_str("];\n");
    o
}

#[derive(serde::Serialize)]
struct JsonManifest<'a> {
    services: &'a [Service],
}

fn json(services: &[Service]) -> String {
    // Serializing plain strings and vecs can't fail.
    let mut out = serde_json::to_string_pretty(&JsonManifest { services }).unwrap_or_default();
    out.push('\n');
    out
}
